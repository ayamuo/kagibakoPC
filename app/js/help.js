/**
 * 実行環境に合わせて、出す節・行・質問を選ぶ
 * isDesktop: Windows の PC版アプリ / isAndroid: Android版アプリ / isPhone: スマホの画面（Android か、幅の狭い画面）
 */
export function forHost(doc, { isDesktop = false, isAndroid = false, isPhone = false } = {}) {
  const fits = (o) => !!o && !((o.pc && !isDesktop) || (o.android && !isAndroid) || (o.wide && isPhone) || (o.phone && !isPhone));
  const line = (x) => (typeof x === 'string' ? x : fits(x) ? x.t : null);
  const qa = ([q, a, o]) => (!o || fits(o) ? [q, a] : null);
  return {
    ...doc,
    intro: isPhone && doc.introPhone ? doc.introPhone : doc.intro,
    sections: doc.sections.filter(fits).map((s) => ({
      ...s,
      list: s.list?.map(line).filter(Boolean),
      items: s.items?.map(qa).filter(Boolean),
    })).filter((s) => s.list?.length || s.items?.length || s.p?.length),
  };
}
